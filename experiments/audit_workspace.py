def audit_links():
    failures = []
    documents = [path for path in ROOT.rglob("*.md")
                 if "__pycache__" not in path.parts
                 and not release_excluded(path.relative_to(ROOT))]
    for document in documents:
        for target in re.findall(r"\[[^\]]*\]\(([^)\s]+)\)", document.read_text("utf-8-sig")):
            if "://" in target or target.startswith(("#", "mailto:")):
                continue
            path = target.split("#", 1)[0]
            if not path:
                continue
            resolved = (document.parent / path).resolve()
            try:
                relative = resolved.relative_to(ROOT).as_posix()
            except ValueError:
                failures.append({"document": document.name, "target": target, "reason": "outside_project"})
                continue
            if release_excluded(relative):
                failures.append({"document": document.name, "target": target, "reason": "local_only_target"})
            elif not resolved.exists():
                failures.append({"document": document.name, "target": target, "reason": "missing_target"})
    return failures


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    args = parser.parse_args()
    records = collect()
    content = render(records)
    target = ROOT / "CODE_MAP.md"
    if args.write:
        target.write_text(content, encoding="utf-8")
    if not target.is_file() or target.read_text("utf-8") != content:
        raise SystemExit("CODE_MAP.md is stale; run the audit with --write")
    manifest_path = ROOT / "artifacts.manifest.json"
    manifest = json.loads(manifest_path.read_text("utf-8"))["artifacts"] if manifest_path.is_file() else {}
    available = []
    failures = []
    for name, expected in manifest.items():
        path = ROOT / name
        if not path.is_file():
            continue
        available.append(name)
        actual = hashlib.sha256(path.read_bytes()).hexdigest()
        if actual != expected:
            failures.append(name)
    links = audit_links()
    summary = {"modules": len(records), "local_link_errors": links,
               "manifest_entries": len(manifest), "assets_available": len(available),
               "assets_missing": len(manifest) - len(available),
               "manifest_failures": failures}
    print(json.dumps(summary, indent=2))
    if summary["local_link_errors"] or summary["manifest_failures"]:
        raise SystemExit(1)


if __name__ == "__main__":
    main()
