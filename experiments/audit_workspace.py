"""Build/check the maintained Python code map, local links, and available assets.

The checker does not modify research outputs or remove local data. ``--write``
updates only CODE_MAP.md. Asset hashes are checked when the corresponding local
asset exists; source releases intentionally omit those large external assets.
"""
