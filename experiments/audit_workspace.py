def release_excluded(relative):
    relative = Path(relative).as_posix()
    if relative in PUBLIC_LOCAL_READMES:
        return False
    return any(relative == item or relative.startswith(item + "/") for item in LOCAL_ONLY_RELEASE_PATHS)


def module_name(path):
    parts = list(path.with_suffix("").parts)
    if parts[-1] == "__init__":
        parts.pop()
    return ".".join(parts)


def category(path):
    if path.parts[0] == "tools":
        return "Project maintenance and release checks"
    if path.parts[0] == "tests":
        return "Tests"
    if path.parts[0] == "experiments":
        return "Research and reproduction commands"
    if path.parent.name == "llm":
        return "Language backend interfaces and implementations"
    if path.stem in CURRENT:
        return "Current evaluation and CKKS prototypes"
    if path.stem in SHARED or path.stem in {"canr", "ciphertext_tensor", "dp_accountant"}:
        return "Shared runtime and audit infrastructure"
    return "Retained encoder, release and decoder baselines"


def collect():
    files = sorted(p.relative_to(ROOT) for folder in ("fpavlm", "experiments", "tests", "tools")
                   for p in (ROOT / folder).rglob("*.py") if "__pycache__" not in p.parts)
    names = {module_name(p): p for p in files}
    inbound = {p.as_posix(): set() for p in files}
    records = []
    for path in files:
        tree = ast.parse((ROOT / path).read_text("utf-8-sig"))
        symbols = [n.name for n in tree.body if isinstance(n, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef))
                   and not n.name.startswith("_")]
        imports = set()
        package = module_name(path) if path.stem == "__init__" else module_name(path).rpartition(".")[0]
        for node in ast.walk(tree):
            if isinstance(node, ast.Import):
                imports.update(a.name for a in node.names)
            elif isinstance(node, ast.ImportFrom):
                base = node.module or ""
                if node.level:
                    base = importlib.util.resolve_name("." * node.level + base, package)
                imports.add(base)
                imports.update(base + "." + a.name for a in node.names)
        for name in imports:
            if name in names:
                inbound[names[name].as_posix()].add(path.as_posix())
        purpose = ast.get_docstring(tree)
        purpose = purpose.splitlines()[0].strip() if purpose else (
            "Regression tests." if path.parts[0] == "tests" else "Maintenance helper."
        )
        records.append({"path": path.as_posix(), "role": category(path), "purpose": purpose,
                        "symbols": symbols})
    for record in records:
        record["imported_by"] = sorted(inbound[record["path"]])
    return records


